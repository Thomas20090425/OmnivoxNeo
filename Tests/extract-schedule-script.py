#!/usr/bin/env python3
"""Regenerate Tests/MonthViewCardHarness.js from the shipping scraper.

The events webpart renders two completely different trees and the app has to
read both, which is easy to break and impossible to check by eye. This lifts
the real script out of `AppModel.extractSchedule` and the real selectors out
of `PortalConventions`, so the harness beside it exercises what actually
ships rather than a copy that drifts.

    python3 -I Tests/extract-schedule-script.py
    # then serve Tests/ and open MonthViewCardFixture.html

Run from the repository root.
"""

import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
APP_MODEL = ROOT / "OmnivoxNeo/Services/AppModel.swift"
CONVENTIONS = ROOT / "OmnivoxNeo/Schools/PortalConventions.swift"
HARNESS = ROOT / "Tests/MonthViewCardHarness.js"

INTERPOLATION = "\\#(institution.conventions.javascriptDescriptor)"


def extraction_script(source: str) -> str:
    start = source.index("private func extractSchedule(attempt: Int)")
    opening = source.index('let script = #"""', start) + len('let script = #"""')
    closing = source.index('"""#', opening)
    return source[opening:closing]


def selectors(source: str) -> dict:
    """The `javascriptDescriptor` dictionary, resolved to its declared defaults."""
    descriptor = source[source.index("var javascriptDescriptor"):]
    pairs = re.findall(r'"([A-Za-z]+)":\s*([A-Za-z]+)', descriptor)
    resolved = {}
    for key, prop in pairs:
        match = re.search(
            r'var %s:\s*String\s*=\s*\n?\s*#?"(.*?)"#?\s*\n' % re.escape(prop),
            source,
            re.S,
        )
        if match:
            resolved[key] = match.group(1).strip()
    missing = [key for key, _ in pairs if key not in resolved]
    if missing:
        raise SystemExit(f"could not resolve selectors: {', '.join(missing)}")
    return resolved


def main() -> int:
    script = extraction_script(APP_MODEL.read_text())
    fields = selectors(CONVENTIONS.read_text())
    script = script.replace(INTERPOLATION, json.dumps(fields, sort_keys=True))
    if "\\#(" in script:
        raise SystemExit("an interpolation was left unsubstituted")
    HARNESS.write_text(
        "// Generated by Tests/extract-schedule-script.py from\n"
        "// AppModel.extractSchedule. Regenerate it rather than editing it,\n"
        "// so the fixture always exercises the script the app ships.\n"
        "window.__neoExtract = async () => " + script.strip() + ";\n"
    )
    print(f"wrote {HARNESS.relative_to(ROOT)} ({len(fields)} selectors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
